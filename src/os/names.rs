pub fn lvo_name(table: &[&str], lvo_index: usize) -> String {
    table
        .get(lvo_index)
        .map(|s| s.to_string())
        .unwrap_or_else(|| format!("LVO_{}", -(30 + 6 * lvo_index as i32)))
}
